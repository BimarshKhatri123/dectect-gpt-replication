"""
llm_judge.py -- LLM-as-judge evaluation (COMP8240 extension).

The judge is used in two roles:
  1. detect : a zero-shot "was this written by a human or an AI?" classifier, compared with
              DetectGPT on exactly the same pairs (same AUROC metric).
  2. quality: a holistic 1-6 essay score (PERSUADE rubric scale). On human essays it is
              validated against the expert holistic scores shipped with PERSUADE 2.0; on
              machine essays it checks that the constructed data is fluent and on-task.

Scores are read from the judge's next-token probabilities rather than from free text, so
every text gets a continuous score (needed for AUROC) and no output parsing can fail:
  p_ai    = P("AI" option) / (P("human" option) + P("AI" option)), averaged over the two
            answer orderings (A=human/B=AI and A=AI/B=human) to cancel letter-position bias.
  quality = expected value of the digits 1..6 under the judge's distribution.

    python llm_judge.py --pairs data/new/persuade_paired_qwen2.5-1.5b.csv --judge microsoft/Phi-3.5-mini-instruct --n 200
Output: results/llm_judge/<pairs-stem>__<judge>.csv  (+ _summary.json)
"""
import argparse
import json
import os

import numpy as np
import pandas as pd
import torch
from sklearn.metrics import roc_auc_score
from tqdm import tqdm

DETECT_TMPL = (
    "{context}Some texts like this are written by people and some are generated by an AI language "
    "model such as ChatGPT.\n\nText:\n\"\"\"\n{text}\n\"\"\"\n\n"
    "Was this text written by a human or generated by an AI?\n"
    "A: {opt_a}\nB: {opt_b}\n"
    "Answer with a single letter (A or B)."
)
QUALITY_TMPL = (
    "You are an experienced teacher scoring a persuasive essay written for this assignment:\n"
    "\"{prompt_name}\"\n\nEssay:\n\"\"\"\n{text}\n\"\"\"\n\n"
    "Score the essay holistically from 1 to 6 (1 = very little mastery, 2 = little mastery, "
    "3 = developing mastery, 4 = adequate mastery, 5 = reasonably consistent mastery, 6 = clear and "
    "consistent mastery), considering point of view, use of evidence and examples, organisation, "
    "language use and conventions. Note that the essay may have been cut off at 250 words; do not "
    "penalise the missing ending.\nAnswer with a single digit (1-6)."
)


def option_ids(tok, symbols):
    """Token ids that can encode each symbol as the first answer token ("A" and " A" differ)."""
    ids = []
    for s in symbols:
        cand = {tok.encode(s, add_special_tokens=False)[-1], tok.encode(" " + s, add_special_tokens=False)[-1]}
        ids.append(sorted(cand))
    return ids


@torch.no_grad()
def next_token_logprobs(model, tok, user_msg, ids):
    chat = tok.apply_chat_template([{"role": "user", "content": user_msg}], tokenize=False, add_generation_prompt=True)
    enc = tok(chat, return_tensors="pt", add_special_tokens=False).to(model.device)
    logits = model(**enc).logits[0, -1].float()
    logp = torch.log_softmax(logits, -1)
    per_option = torch.stack([torch.logsumexp(logp[i], 0) for i in ids])   # log P(option)
    mass = per_option.exp().sum().item()                                   # how much prob. the judge put on valid answers
    return torch.log_softmax(per_option, 0).cpu().numpy(), mass


def load_judge(name, cache_dir, gpu_mem):
    from transformers import AutoModelForCausalLM, AutoTokenizer
    tok = AutoTokenizer.from_pretrained(name, cache_dir=cache_dir)
    model = AutoModelForCausalLM.from_pretrained(
        name, torch_dtype=torch.float16, cache_dir=cache_dir, device_map="auto",
        max_memory={0: gpu_mem, "cpu": "48GiB"}, attn_implementation="eager").eval()
    return model, tok


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pairs", required=True, help="CSV with `human` and `machine` columns")
    ap.add_argument("--judge", default="microsoft/Phi-3.5-mini-instruct")
    ap.add_argument("--n", type=int, default=200, help="number of pairs (first n rows, as in run.py)")
    ap.add_argument("--tasks", default="detect,quality")
    ap.add_argument("--context", default="auto", help="'essay', 'answer' or 'auto' (from file name)")
    ap.add_argument("--cache_dir", default="../cache")
    ap.add_argument("--gpu_mem", default="6.5GiB", help="VRAM budget; layers beyond it are offloaded to CPU")
    ap.add_argument("--out_dir", default="results/llm_judge")
    args = ap.parse_args()

    pairs = pd.read_csv(args.pairs).head(args.n)
    is_essay = (args.context == "essay") or (args.context == "auto" and "hc3" not in os.path.basename(args.pairs))
    context = ("Below is a short argumentative essay written for a school assignment. " if is_essay
               else "Below is an answer to a question. ")
    tasks = args.tasks.split(",")
    if not is_essay and "quality" in tasks:
        tasks.remove("quality")   # the 1-6 essay rubric only makes sense for essays

    model, tok = load_judge(args.judge, args.cache_dir, args.gpu_mem)
    ab_ids, digit_ids = option_ids(tok, ["A", "B"]), option_ids(tok, list("123456"))

    rows = []
    for i, r in tqdm(list(pairs.iterrows()), desc=f"judging with {args.judge}"):
        for label in ("human", "machine"):
            text = " ".join(str(r[label]).split())
            row = dict(pair_id=r.get("pair_id", i), label=label, prompt_name=r.get("prompt_name", ""),
                       holistic_score=r.get("holistic_score", np.nan) if label == "human" else np.nan)
            if "detect" in tasks:
                lp1, m1 = next_token_logprobs(model, tok, DETECT_TMPL.format(
                    context=context, text=text, opt_a="written by a human", opt_b="generated by an AI"), ab_ids)
                lp2, m2 = next_token_logprobs(model, tok, DETECT_TMPL.format(
                    context=context, text=text, opt_a="generated by an AI", opt_b="written by a human"), ab_ids)
                p1, p2 = np.exp(lp1[1]), np.exp(lp2[0])           # P(AI) under each ordering
                row.update(p_ai=(p1 + p2) / 2, p_ai_order1=p1, p_ai_order2=p2, valid_mass_detect=(m1 + m2) / 2)
            if "quality" in tasks:
                lp, m = next_token_logprobs(model, tok, QUALITY_TMPL.format(
                    prompt_name=r.get("prompt_name", "a persuasive essay"), text=text), digit_ids)
                probs = np.exp(lp)
                row.update(quality=float((probs * np.arange(1, 7)).sum()), quality_argmax=int(probs.argmax()) + 1,
                           valid_mass_quality=m)
            rows.append(row)

    df = pd.DataFrame(rows)
    os.makedirs(args.out_dir, exist_ok=True)
    stem = f"{os.path.splitext(os.path.basename(args.pairs))[0]}__{args.judge.split('/')[-1]}"
    df.to_csv(os.path.join(args.out_dir, stem + ".csv"), index=False)

    y = (df.label == "machine").astype(int)
    summary = dict(pairs=args.pairs, judge=args.judge, n_pairs=len(pairs))
    if "detect" in tasks:
        summary.update(auroc=roc_auc_score(y, df.p_ai), accuracy_at_0_5=float(((df.p_ai > 0.5) == y).mean()),
                       auroc_order1=roc_auc_score(y, df.p_ai_order1), auroc_order2=roc_auc_score(y, df.p_ai_order2),
                       frac_called_ai=float((df.p_ai > 0.5).mean()), mean_valid_mass=float(df.valid_mass_detect.mean()))
    if "quality" in tasks:
        h = df[df.label == "human"]
        summary.update(quality_mean_human=float(h.quality.mean()),
                       quality_mean_machine=float(df[df.label == "machine"].quality.mean()),
                       spearman_quality_vs_expert=float(h[["quality", "holistic_score"]].corr("spearman").iloc[0, 1])
                       if h.holistic_score.notna().any() else None)
    with open(os.path.join(args.out_dir, stem + "_summary.json"), "w") as f:
        json.dump(summary, f, indent=2)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
